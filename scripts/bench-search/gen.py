# Regenerate after-customers.sql and after-articles.sql: SEARCH_CUSTOMERS_SQL
# and SEARCH_ARTICLES_SQL rebuilt from the Rust source (string continuations,
# format! arguments, the constants in search.rs) as pgbench scripts that run
# a search the way cxp-core does: the search, then the page's rows (#34
# retired the backlog batch that used to run first). Only newlines are replaced (pgbench wants one line per
# statement): spaces inside string literals such as '  %' are kept. Run
# after changing either statement:
#
#   python3 scripts/bench-search/gen.py . scripts/bench-search
import re, sys
W = sys.argv[1] + '/crates/cxp-core/src/'
OUT = sys.argv[2]
def lit(src, name):
    i = src.index(name + ': LazyLock')
    j = src.index('format!(', i); k = src.index('"', j)
    out = []; p = k + 1
    while True:
        c = src[p]
        if c == '\\':
            n = src[p+1]
            if n == '\n':
                p += 2
                while src[p] in ' \t': p += 1
                continue
            out.append({'\\': '\\', '"': '"', 'n': '\n'}[n]); p += 2; continue
        if c == '"': break
        out.append(c); p += 1
    end = src.index('});', p)
    args = dict(re.findall(r'(\w+) = ([^,\n]+),', src[p:end]))
    return ''.join(out), args
consts = {}
for m in re.finditer(r'pub(?:\(crate\))? const (\w+): i64 = ([\d_]+);', open(W + 'search.rs').read()):
    consts[m.group(1)] = int(m.group(2).replace('_', ''))
def expand(sql, args):
    env = dict(consts); env['cap'] = consts['TOTAL_CAP']
    for k, v in args.items():
        env[k] = eval(v.strip(), {}, env)
    return re.sub(r'\{(\w+)\}', lambda m: str(env[m.group(1)]), sql.replace('{{', '\x00').replace('}}', '\x01')).replace('\x00', '{').replace('\x01', '}')
cust = open(W + 'customers.rs').read(); kb = open(W + 'knowledge.rs').read()
cols_c = re.sub(r'\\\n\s*', '', re.search(r'CUSTOMER_COLS: &str = "(.*?)";', cust, re.S).group(1))
cols_k = re.search(r'ARTICLE_COLS: &str =\s*"(.*?)";', kb, re.S).group(1)
c = expand(*lit(cust, 'SEARCH_CUSTOMERS_SQL'))
k = expand(*lit(kb, 'SEARCH_ARTICLES_SQL'))
def sub(sql, m):
    for n in sorted(m, reverse=True): sql = sql.replace('$%d' % n, m[n])
    return sql
c = sub(c, {1: ':org::uuid', 2: ':pat', 3: ':q', 4: '50::bigint', 5: '0::bigint'})
k = sub(k, {1: ':org::uuid', 2: ':q', 3: ':pat', 4: '20::bigint'})
def script(what, table, sql, cols):
    return (f"-- search_{what} after #17, as cxp_core runs it. Generated by gen.py; do not edit.\n"
            "BEGIN;\nSET LOCAL ROLE otto_app;\nSELECT set_config('app.org_id', :org, true);\n"
            "SET LOCAL jit = off;\nSET LOCAL statement_timeout = '2s';\n"
            + sql.replace("\n", " ").strip() + ' \\gset\n'
            f"SELECT {cols} FROM {table} WHERE org_id = :org::uuid AND id = ANY (:ids::uuid[]);\n"
            "COMMIT;\n")
open(OUT + '/after-customers.sql', 'w').write(script('customers', 'customers', c, cols_c))
open(OUT + '/after-articles.sql', 'w').write(script('articles', 'knowledge_articles', k, cols_k))
